#!/usr/bin/env node
/**
 * TravelSuite360 · big reveal positions (Spec §08 "Big reveal"). Deterministic: mulberry32,
 * seed 360. Writes `src/data/ts-reveal.ts` (committed); nothing is random at runtime.
 *
 *   node scripts/gen-ts-reveal.mjs           write the file
 *   node scripts/gen-ts-reveal.mjs --check   exit 1 if the committed file differs
 *
 * Rules (Spec §08):
 * - desktop: 64 fragments, 4 depth groups (z 0 / −300 / −600 / −900), 16 each, camera → −800;
 *   mobile: 32 fragments, 2 groups (z 0 / −600), camera → −500.
 * - spread per group scaled by (P − z)/P (P = 1400, z = the group's depth once the camera has
 *   retreated): sampled in the final frame, then unprojected, so far groups still fill it.
 * - none inside the central clear ellipse (480×300 desktop, 300×340 mobile) at the final frame.
 * - the fragments exist from the start and appear through the camera retreat, not by fading
 *   (Revelado 2.2 §10): none lies inside 80% of the frame before the retreat begins.
 * - in a group, fragments never overlap in the final frame.
 * - words cycle through the six Content Master words.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SEED = 360;
export const P = 1400;
/** Content Master 06 · reveal (checked against projects.ts by the tests) */
export const WORDS = ["mensaje", "cotización", "viaje", "reserva", "cliente", "reporte"];
/** group index → translateZ inside the camera */
export const GROUP_Z = [0, -300, -600, -900];

export const VARIANTS = {
  desktop: { w: 1440, h: 900, groups: [0, 1, 2, 3], perGroup: 16, camEnd: -800, clear: { rx: 240, ry: 150 }, margin: 24 },
  mobile: { w: 390, h: 844, groups: [0, 2], perGroup: 16, camEnd: -500, clear: { rx: 150, ry: 170 }, margin: 12 },
};

/** a 9px mono word: ≈ 5.6 px per character, 14 px with its rule */
const box = (word) => ({ w: Math.ceil(word.length * 5.6), h: 14 });

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** perceived scale of a plane at total depth z */
const k = (z) => P / (P - z);

export function generate() {
  const rand = mulberry32(SEED);
  const out = {};
  for (const [name, v] of Object.entries(VARIANTS)) {
    const cx = v.w / 2;
    const cy = v.h / 2;
    const list = [];
    let n = 0;
    for (const group of v.groups) {
      const z = GROUP_Z[group];
      const kEnd = k(z + v.camEnd);
      const kStart = k(z);
      const placed = [];
      for (let i = 0; i < v.perGroup; i++) {
        const word = WORDS[n % WORDS.length];
        const b = box(word);
        let found = null;
        for (let tries = 0; tries < 20000 && !found; tries++) {
          // in the final frame (projected coordinates)
          const X = v.margin + rand() * (v.w - 2 * v.margin - b.w);
          const Y = v.margin + rand() * (v.h - 2 * v.margin - b.h);
          const ex = (X + b.w / 2 - cx) / v.clear.rx;
          const ey = (Y + b.h / 2 - cy) / v.clear.ry;
          if (ex * ex + ey * ey < 1) continue;
          // before the retreat: outside 80% of the frame
          const sx = cx + (X - cx) * (kStart / kEnd);
          const sy = cy + (Y - cy) * (kStart / kEnd);
          const inside = (px, py) => Math.abs(px - cx) < 0.8 * cx && Math.abs(py - cy) < 0.8 * cy;
          if (inside(sx, sy) || inside(sx + b.w * (kStart / kEnd), sy + b.h * (kStart / kEnd))) continue;
          const pad = 12;
          if (placed.some((p) => X < p.X + p.w + pad && p.X < X + b.w + pad && Y < p.Y + p.h + pad && p.Y < Y + b.h + pad)) continue;
          found = { X, Y };
        }
        if (!found) throw new Error(`${name}: no room for fragment ${n} (group ${group})`);
        placed.push({ ...found, w: b.w, h: b.h });
        // unproject into the group's own plane (static left / top, never animated)
        const x = Math.round(cx + (found.X - cx) / kEnd);
        const y = Math.round(cy + (found.Y - cy) / kEnd);
        list.push({ id: `${name[0]}${String(n).padStart(2, "0")}`, group, x, y, word });
        n++;
      }
    }
    out[name] = list;
  }
  return out;
}

export function render(data) {
  const rows = (list) => list.map((f) => `    { id: "${f.id}", group: ${f.group}, x: ${f.x}, y: ${f.y}, word: "${f.word}" },`).join("\n");
  return `// Generated by scripts/gen-ts-reveal.mjs (mulberry32, seed ${SEED}). Do not edit: run the script.
// TravelSuite360 big reveal (Spec §08): fragment positions in each group's own plane, in the
// world's design space (desktop 1440×900, mobile 390×844). Groups: index into TS_GROUP_Z.

export interface RevealFragment {
  id: string;
  /** depth group: 0 / 1 / 2 / 3 → translateZ ${GROUP_Z.join(" / ")} */
  group: number;
  x: number;
  y: number;
  word: string;
}

export const TS_GROUP_Z = [${GROUP_Z.join(", ")}] as const;

export const TS_REVEAL: { desktop: RevealFragment[]; mobile: RevealFragment[] } = {
  desktop: [
${rows(data.desktop)}
  ],
  mobile: [
${rows(data.mobile)}
  ],
};
`;
}

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, "../src/data/ts-reveal.ts");

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(generate());
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
    } catch {
      // missing file: differs
    }
    if (current !== text) {
      console.error("src/data/ts-reveal.ts is out of date: run node scripts/gen-ts-reveal.mjs");
      process.exit(1);
    }
    console.log("ts-reveal: up to date");
  } else {
    writeFileSync(target, text);
    console.log(`ts-reveal: ${target} (desktop ${generate().desktop.length}, mobile ${generate().mobile.length})`);
  }
}
